-- DEMONSTRAÇÃO SQL COMPLEMENTAR de BEGIN TRANSACTION / COMMIT / ROLLBACK.
-- Executar SEPARADAMENTE do roteiro da API, em banco próprio (ex.: GS_CSHARP_ZELADORIA_DEMO)
-- recém-criado com 01 e 02. Não executar sobre dados que precisem ser preservados. Sem reset automático.
SET XACT_ABORT ON;

IF (SELECT QUANTIDADEPENDENTE FROM OCORRENCIA WHERE ID = 1) <> 20
   OR EXISTS (SELECT 1 FROM ATENDIMENTO_OCORRENCIA WHERE OCORRENCIAID = 1)
    THROW 51000, 'A demonstracao exige ocorrencia 1 com 20 pendentes e zero atendimentos.', 1;

SELECT 'ANTES' AS ETAPA, QUANTIDADEPENDENTE, SITUACAO,
       (SELECT COUNT(*) FROM ATENDIMENTO_OCORRENCIA WHERE OCORRENCIAID = 1) AS ATENDIMENTOS
FROM OCORRENCIA WHERE ID = 1;  -- 20.000 / ABERTA / 0

-- Prova 1: duas escritas confirmadas juntas (COMMIT)
BEGIN TRY
    BEGIN TRANSACTION;
        UPDATE OCORRENCIA
           SET QUANTIDADEPENDENTE = QUANTIDADEPENDENTE - 3,
               SITUACAO = CASE WHEN QUANTIDADEPENDENTE - 3 = 0 THEN N'CONCLUIDA' ELSE N'EM_ATENDIMENTO' END
         WHERE ID = 1 AND SITUACAO <> N'CONCLUIDA' AND QUANTIDADEPENDENTE >= 3;
        IF @@ROWCOUNT <> 1 THROW 51001, 'Pendente insuficiente.', 1;
        INSERT INTO ATENDIMENTO_OCORRENCIA (OCORRENCIAID, QUANTIDADE, EQUIPECAMPOCODIGO, EQUIPERM, EXECUTOR, CRIADOUTC)
        VALUES (1, 3, N'EQ_ZEL_MOOCA_SQL', N'556095', N'VitorCardoso_RM556404', SYSUTCDATETIME());
    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;

SELECT 'APOS_COMMIT' AS ETAPA, QUANTIDADEPENDENTE, SITUACAO,
       (SELECT COUNT(*) FROM ATENDIMENTO_OCORRENCIA WHERE OCORRENCIAID = 1) AS ATENDIMENTOS
FROM OCORRENCIA WHERE ID = 1;  -- 17.000 / EM_ATENDIMENTO / 1

-- Prova 2: falha DEPOIS do UPDATE e do INSERT, antes do COMMIT (ROLLBACK desfaz ambos)
BEGIN TRY
    BEGIN TRANSACTION;
        UPDATE OCORRENCIA
           SET QUANTIDADEPENDENTE = QUANTIDADEPENDENTE - 2,
               SITUACAO = CASE WHEN QUANTIDADEPENDENTE - 2 = 0 THEN N'CONCLUIDA' ELSE N'EM_ATENDIMENTO' END
         WHERE ID = 1 AND SITUACAO <> N'CONCLUIDA' AND QUANTIDADEPENDENTE >= 2;
        IF @@ROWCOUNT <> 1 THROW 51002, 'Pendente insuficiente.', 1;
        INSERT INTO ATENDIMENTO_OCORRENCIA (OCORRENCIAID, QUANTIDADE, EQUIPECAMPOCODIGO, EQUIPERM, EXECUTOR, CRIADOUTC)
        VALUES (1, 2, N'EQ_ZEL_MOOCA_SQL', N'556095', N'VitorCardoso_RM556404', SYSUTCDATETIME());
        SELECT 'DENTRO_DA_TRANSACAO' AS ETAPA, QUANTIDADEPENDENTE,
               (SELECT COUNT(*) FROM ATENDIMENTO_OCORRENCIA WHERE OCORRENCIAID = 1) AS ATENDIMENTOS
        FROM OCORRENCIA WHERE ID = 1;  -- 15.000 / 2 (ainda não confirmado)
        THROW 51003, 'Falha didatica depois do UPDATE e do INSERT.', 1;
    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    IF ERROR_NUMBER() <> 51003 THROW;
    SELECT ERROR_MESSAGE() AS FALHA_ESPERADA;
END CATCH;

SELECT 'APOS_ROLLBACK' AS ETAPA, QUANTIDADEPENDENTE, SITUACAO,
       (SELECT COUNT(*) FROM ATENDIMENTO_OCORRENCIA WHERE OCORRENCIAID = 1) AS ATENDIMENTOS
FROM OCORRENCIA WHERE ID = 1;  -- permanece 17.000 / EM_ATENDIMENTO / 1
