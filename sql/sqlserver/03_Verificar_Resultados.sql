-- Consultas de verificação (somente leitura). Pode ser executado quantas vezes quiser:
-- após a carga (linha de base), após upload (bytes), após COMMIT e após ROLLBACK.

SELECT @@SERVERNAME AS SERVIDOR_INSTANCIA, DB_NAME() AS BANCO, SYSUTCDATETIME() AS CONSULTA_UTC;

-- Contagem por tabela
SELECT 'REGIAO' AS TABELA, COUNT(*) AS LINHAS FROM REGIAO
UNION ALL SELECT 'CATEGORIA_OCORRENCIA', COUNT(*) FROM CATEGORIA_OCORRENCIA
UNION ALL SELECT 'OCORRENCIA', COUNT(*) FROM OCORRENCIA
UNION ALL SELECT 'IMAGEM_OCORRENCIA', COUNT(*) FROM IMAGEM_OCORRENCIA
UNION ALL SELECT 'ATENDIMENTO_OCORRENCIA', COUNT(*) FROM ATENDIMENTO_OCORRENCIA;

-- Saldo pendente x atendimentos (consistência: ESTIMADA = PENDENTE + SOMA ATENDIDA)
SELECT o.ID AS OCORRENCIAID, o.UNIDADE, o.QUANTIDADEESTIMADA, o.QUANTIDADEPENDENTE, o.SITUACAO,
       COUNT(a.ID) AS ATENDIMENTOS, COALESCE(SUM(a.QUANTIDADE), 0) AS QUANTIDADE_ATENDIDA,
       CASE WHEN o.QUANTIDADEESTIMADA = o.QUANTIDADEPENDENTE + COALESCE(SUM(a.QUANTIDADE), 0)
            THEN 'SIM' ELSE 'NAO' END AS CONSISTENTE
FROM OCORRENCIA o
LEFT JOIN ATENDIMENTO_OCORRENCIA a ON a.OCORRENCIAID = o.ID
GROUP BY o.ID, o.UNIDADE, o.QUANTIDADEESTIMADA, o.QUANTIDADEPENDENTE, o.SITUACAO
ORDER BY o.ID;

-- Atendimentos gravados (identificação da equipe e do executor)
SELECT ID, OCORRENCIAID, QUANTIDADE, EQUIPECAMPOCODIGO, EQUIPERM, EXECUTOR, CRIADOUTC
FROM ATENDIMENTO_OCORRENCIA ORDER BY ID;

-- Imagens: bytes REAIS no banco (DATALENGTH) e hash SHA-256 calculado pelo próprio SQL Server
SELECT i.ID, i.OCORRENCIAID, o.TITULO AS OCORRENCIA, i.TITULO, i.NOMEARQUIVO, i.MIME,
       i.TAMANHOBYTES, DATALENGTH(i.DADOS) AS BYTES_NO_BANCO,
       i.HASHSHA256 AS HASH_GRAVADO_PELA_API,
       CONVERT(char(64), HASHBYTES('SHA2_256', i.DADOS), 2) AS HASH_CALCULADO_NO_BANCO,
       CONVERT(varchar(20), SUBSTRING(i.DADOS, 1, 8), 1) AS PRIMEIROS_BYTES,
       i.EQUIPERM, i.EXECUTOR, i.ENVIADAUTC
FROM IMAGEM_OCORRENCIA i
JOIN OCORRENCIA o ON o.ID = i.OCORRENCIAID
ORDER BY i.ID;

-- Restrições do modelo físico (PK/FK/CHECK)
SELECT fk.name AS FK, OBJECT_NAME(fk.parent_object_id) AS TABELA_FILHA,
       OBJECT_NAME(fk.referenced_object_id) AS TABELA_PAI, fk.delete_referential_action_desc AS AO_EXCLUIR
FROM sys.foreign_keys fk ORDER BY TABELA_FILHA, FK;

SELECT OBJECT_NAME(parent_object_id) AS TABELA, name AS CHECK_CONSTRAINT, definition AS REGRA
FROM sys.check_constraints ORDER BY TABELA, CHECK_CONSTRAINT;
